# دالة البحث المرن
def search_text(text, keyword):
    results = []
    def normalize(t):
        return (t.replace('أ', 'ا')
                 .replace('إ', 'ا')
                 .replace('آ', 'ا')
                 .replace('ة', 'ه')
                 .replace('ى', 'ي'))
    
    normalized_keyword = normalize(keyword.strip())
    lines = text.split('\n')
    
    for line in lines:
        if normalized_keyword and normalized_keyword in normalize(line):
            results.append(line.strip())
    return results

